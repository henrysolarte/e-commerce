#!/bin/sh
# convert-database-url.sh
# Converts Render's DATABASE_URL to Spring Boot JDBC properties
# and writes them to a properties file that Spring Boot will read

PROPS_FILE="/app/application-render.properties"

echo "=== DATABASE_URL Converter ==="
echo "INPUT DATABASE_URL: $DATABASE_URL"

if [ -z "$DATABASE_URL" ]; then
  echo "No DATABASE_URL set, using defaults"
  SPRING_DATASOURCE_URL="jdbc:postgresql://localhost:5432/ecommerce"
  SPRING_DATASOURCE_USERNAME="postgres"
  SPRING_DATASOURCE_PASSWORD="postgres"
else
  echo "Converting DATABASE_URL to JDBC format..."
  
  # Remove postgresql:// prefix
  URL_NO_PREFIX=$(echo "$DATABASE_URL" | sed 's|postgresql://||')
  
  # Extract user and password
  USER_PASS=$(echo "$URL_NO_PREFIX" | cut -d '@' -f 1)
  HOST_DB=$(echo "$URL_NO_PREFIX" | cut -d '@' -f 2)
  
  # Extract username and password
  USERNAME=$(echo "$USER_PASS" | cut -d ':' -f 1)
  PASSWORD=$(echo "$USER_PASS" | cut -d ':' -f 2-)
  
  # Extract host and port
  HOST_PORT=$(echo "$HOST_DB" | cut -d '/' -f 1)
  DB_NAME=$(echo "$HOST_DB" | cut -d '/' -f 2)
  
  # Split host and port
  if echo "$HOST_PORT" | grep -q ':'; then
    HOST=$(echo "$HOST_PORT" | cut -d ':' -f 1)
    PORT=$(echo "$HOST_PORT" | cut -d ':' -f 2)
  else
    HOST="$HOST_PORT"
    PORT="5432"
  fi
  
  # Build JDBC URL
  SPRING_DATASOURCE_URL="jdbc:postgresql://$HOST:$PORT/$DB_NAME"
  SPRING_DATASOURCE_USERNAME="$USERNAME"
  SPRING_DATASOURCE_PASSWORD="$PASSWORD"
  
  echo "Database configuration:"
  echo "  Host: $HOST"
  echo "  Port: $PORT"
  echo "  Database: $DB_NAME"
  echo "  Username: $USERNAME"
  echo "  Password length: $(echo -n "$PASSWORD" | wc -c) chars"
  echo "  JDBC URL: $SPRING_DATASOURCE_URL"
fi

# Write configuration to properties file
cat > "$PROPS_FILE" << EOF
# Auto-generated by convert-database-url.sh
# Server configuration
server.port=${PORT:8081}
server.address=0.0.0.0
server.servlet.context-path=/

# Database configuration
spring.datasource.url=$SPRING_DATASOURCE_URL
spring.datasource.username=$SPRING_DATASOURCE_USERNAME
spring.datasource.password=$SPRING_DATASOURCE_PASSWORD
spring.datasource.driver-class-name=org.postgresql.Driver
spring.datasource.hikari.connection-timeout=10000
spring.datasource.hikari.maximum-pool-size=5

# JPA/Hibernate configuration
spring.jpa.hibernate.ddl-auto=update
spring.jpa.show-sql=false
spring.jpa.properties.hibernate.format_sql=false
spring.jpa.database-platform=org.hibernate.dialect.PostgreSQLDialect

# Logging
logging.level.root=INFO
logging.level.com.parquesoft=DEBUG

# API Documentation (optional - set to false in production if not needed)
springdoc.api-docs.enabled=true
springdoc.swagger-ui.enabled=true
EOF

echo "=== Properties file written to $PROPS_FILE ==="
cat "$PROPS_FILE"

# Export variables for good measure
export SPRING_DATASOURCE_URL
export SPRING_DATASOURCE_USERNAME
export SPRING_DATASOURCE_PASSWORD
